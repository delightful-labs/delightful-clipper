import { expect, it, vi } from 'vitest'
import { createActor, waitFor } from 'xstate'
import { createSignInMachine } from './signin-machine.js'
const accountId = '77777777-7777-4777-8777-777777777777'
it('does not confirm a silently available identity without a completed restoration', () => {
	const connect = vi.fn(async () => {})
	const actor = createActor(createSignInMachine({ connect, connected: () => {} })).start()
	actor.send({ type: 'OBSERVED', observation: { kind: 'ready', accountId } })
	expect(connect).not.toHaveBeenCalled()
	expect(actor.getSnapshot().matches('idle')).toBe(true)
	actor.stop()
})
it('waits for restoration and durable confirmation before closing the popup', async () => {
	const gate = Promise.withResolvers<void>()
	const connect = vi.fn(() => gate.promise)
	const connected = vi.fn()
	const restore = vi.fn()
	const actor = createActor(
		createSignInMachine({ connect, connected, restore: { can: () => true, send: restore } })
	).start()
	actor.send({ type: 'RESTORE', phrase: 'synthetic input' })
	expect(restore).toHaveBeenCalledOnce()
	expect(connect).not.toHaveBeenCalled()
	actor.send({ type: 'OBSERVED', observation: { kind: 'restoring' } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'waiting' } })
	expect(connect).not.toHaveBeenCalled()
	actor.send({ type: 'OBSERVED', observation: { kind: 'ready', accountId } })
	expect(connect).toHaveBeenCalledWith(accountId)
	expect(connected).not.toHaveBeenCalled()
	expect(actor.getSnapshot().can({ type: 'RESTORE', phrase: '' })).toBe(false)
	gate.resolve()
	await waitFor(actor, (s) => s.matches('connected'))
	expect(connected).toHaveBeenCalledOnce()
	actor.stop()
})
it('invalid restoration never confirms the previous local identity', () => {
	const connect = vi.fn(async () => {})
	const actor = createActor(createSignInMachine({ connect, connected: () => {} })).start()
	actor.send({ type: 'OBSERVED', observation: { kind: 'restoring' } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'failed' } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'ready', accountId } })
	expect(connect).not.toHaveBeenCalled()
	actor.stop()
})
it('does not close as connected if the account changes while its confirmation is issued', async () => {
	const gate = Promise.withResolvers<void>()
	const connected = vi.fn()
	const actor = createActor(
		createSignInMachine({ connect: async () => gate.promise, connected })
	).start()
	actor.send({ type: 'OBSERVED', observation: { kind: 'restoring' } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'ready', accountId } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'signed-out' } })
	gate.resolve()
	await waitFor(actor, (s) => s.matches('idle'))
	expect(connected).not.toHaveBeenCalled()
	actor.stop()
})

it('keeps confirmation failure visible and retries only for the account that was restored', async () => {
	const connect = vi
		.fn<(_: string) => Promise<void>>()
		.mockRejectedValueOnce(new Error('storage unavailable'))
		.mockResolvedValue(undefined)
	const connected = vi.fn()
	const actor = createActor(createSignInMachine({ connect, connected })).start()
	actor.send({ type: 'OBSERVED', observation: { kind: 'restoring' } })
	actor.send({ type: 'OBSERVED', observation: { kind: 'ready', accountId } })
	await waitFor(actor, (s) => s.matches('failed'))
	expect(actor.getSnapshot().context.message?.variant).toBe('error')
	expect(connected).not.toHaveBeenCalled()
	actor.send({ type: 'RETRY' })
	await waitFor(actor, (s) => s.matches('connected'))
	expect(connected).toHaveBeenCalledOnce()
	actor.stop()
})

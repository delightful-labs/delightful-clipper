import { writeFile } from 'node:fs/promises'
import { getAuthTables } from 'better-auth/db'
import { jazzAdapter } from 'jazz-tools/better-auth-adapter'
import { atproto } from '@kingironman2011/better-auth-bsky'

// Schema metadata only: no database, credentials, or hosted connection is opened.
const options = { plugins: [atproto({ clientName: 'Delightful Clipper' })] }
const adapter = jazzAdapter({
	db: () => {
		throw new Error('Schema generation must not acquire a database')
	},
	schema: {}
})(options)
const result = await adapter.createSchema({ tables: getAuthTables(options) })
await writeFile(
	new URL('../src/lib/backend/jazz/auth-schema.ts', import.meta.url),
	'// Generated by Jazz alpha.60’s Better Auth adapter for the installed AT Protocol plugin.\n' +
		result.code
)
